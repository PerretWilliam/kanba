#!/bin/sh
# Regenerates Sources/Kanban/Model/Logos.swift from Simple Icons (CC0, https://simpleicons.org).
# Logos are trademarks of their owners; they only identify the AI assigned to a card.
set -e
cd "$(dirname "$0")/.."
OUT=Sources/Kanban/Model/Logos.swift
# slug@version (openai was removed from Simple Icons after v14)
ICONS="claude@16.38.1 openai@14.0.0 googlegemini@16.38.1 githubcopilot@16.38.1 cursor@16.38.1 mistralai@16.38.1 perplexity@16.38.1 meta@16.38.1 deepseek@16.38.1 windsurf@16.38.1 zedindustries@16.38.1 qwen@16.38.1 kimi@16.38.1 cline@16.38.1 opencode@16.38.1"
{
  echo "// Generated by tools/fetch-logos.sh from Simple Icons (CC0). Do not edit."
  echo "enum Logos {"
  echo "    static let svg: [String: String] = ["
  for i in $ICONS; do
    slug=${i%@*}; ver=${i#*@}
    body=$(curl -fsS "https://cdn.jsdelivr.net/npm/simple-icons@$ver/icons/$slug.svg")
    printf '        "%s": #"%s"#,\n' "$slug" "$body"
  done
  echo "    ]"
  echo "}"
} > $OUT
echo "Wrote $OUT"
